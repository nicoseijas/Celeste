namespace Celeste.Wpf.Theming;

/// <summary>
/// The color theme applied to Celeste resources.
/// </summary>
public enum ApplicationTheme
{
    /// <summary>Follow the Windows app theme, and track it while the application runs.</summary>
    System,

    /// <summary>Always use the light theme.</summary>
    Light,

    /// <summary>Always use the dark theme.</summary>
    Dark,
}
